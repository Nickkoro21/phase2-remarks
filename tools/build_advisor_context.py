# cached πρόθεμά τους μένει ΑΠΑΡΑΛΛΑΚΤΟ από αυτόν τον γύρο αλλαγών.
READ_NOTES = """7. **ΟΙ ΔΕΙΚΤΕΣ.** Κανένα εδάφιο εδώ δεν είναι κομμένο, και κανένα δεν τυπώνεται
   δύο φορές. Ο δείκτης **ονοματίζει το id, δεν δίνει κατεύθυνση**:
   - **«η ΠΛΗΡΗΣ απαίτηση είναι στο δικό της μπλοκ «### [id]»»** — ψάξε το id
     μέσα σε αυτό το αρχείο. Μπορεί να είναι **πιο πάνω Ή πιο κάτω** από τον
     δείκτη (τα μπλοκ μπαίνουν κατά σειρά id και κατά αρχείο).
   - **«δεν έχει δικό του μπλοκ … δόθηκε ΠΑΡΑΠΑΝΩ, στην πρώτη ενσωμάτωσή του»**,
     **«ταυτόσημο … με το ΑΥΤΟΛΕΞΕΙ της απαίτησης [id]»**, **«το πλήρες κείμενο
     παραπάνω, με αυτό το id»**, **«Η ΣΚΑΛΑ ΕΙΝΑΙ Η ΙΔΙΑ … παραπάνω»** — εκεί το
     κείμενο είναι όντως **πιο πάνω**.
   Ένα **bullet ενσωμάτωσης** (`• [id] θέμα — …`) σου δίνει το ΑΥΤΟΛΕΞΕΙ της
   παραπομπής· η ΑΠΑΙΤΗΣΗ, οι ΤΙΜΕΣ και η ΔΙΑΔΙΚΑΣΙΑ της ζουν στο μπλοκ
   `### [id]` — εκτός από τα ορφανά ids, που το bullet τα δίνει ΟΛΟΚΛΗΡΑ και το
   λέει ρητά. ΠΟΤΕ μην πεις ότι λείπει κάτι ή ότι το έχεις μισό: πες το id.
8. **ΠΩΣ ΔΙΑΒΑΖΟΝΤΑΙ ΟΙ `ΤΙΜΕΣ:`** — `κλειδί=τιμή · κλειδί=τιμή`. Το `[α, β]`
   είναι λίστα, το `κλειδί:` με εσοχή από κάτω είναι ένθετη ομάδα, το `1)` `2)`
   είναι οι εγγραφές ενός πίνακα **στη σειρά της πηγής**, και το `null` σημαίνει
   «δεν ορίζεται στις πηγές» — όχι μηδέν.
9. **ΟΙ ΣΗΜΕΙΩΣΕΙΣ ΤΗΣ ΨΗΦΙΟΠΟΙΗΣΗΣ (⚠ ΑΛΥΤΟ ΜΕΣΑ ΣΕ ΑΠΑΙΤΗΣΗ).** Κάτω από την
   ΠΗΓΗ πολλών απαιτήσεων υπάρχει μπλοκ **«⚠ ΟΙ ΣΗΜΕΙΩΣΕΙΣ ΤΗΣ ΨΗΦΙΟΠΟΙΗΣΗΣ …
   ΑΜΦΙΒΟΛΙΑ, ΟΧΙ ΚΑΝΟΝΑΣ»**. Είναι ό,τι κατέγραψε η ψηφιοποίηση **για τις
   πηγές**, όχι διάταξη: σιωπή, ασάφεια, αντίφαση ή ένταση μεταξύ των τριών
   πηγών, ασυμμετρία με Phase III/IV, πώς διαβάστηκε ή παράχθηκε μια τιμή — και,
   όπου καταγράφηκε, το **αντίστροφο**: ρητή σύγκλιση δύο πηγών. **ΠΟΤΕ** μην
   παρουσιάσεις σημείωση ως κανόνα και ποτέ μην υπολογίσεις με αριθμό που ζει
   μόνο εκεί. Όταν η ερώτηση πέφτει πάνω σε τέτοια σημείωση, τη **μεταφέρεις**
   με το id της και λες ότι η απόφαση είναι του ιδιοκτήτη — αυτό είναι το
   δυσκολότερο και χρησιμότερο κομμάτι της δουλειάς σου, όχι παράπλευρη πληροφορία.
"""


def main() -> int:
    ap = argparse.ArgumentParser(description="Χτίζει το corpus των agents.")
    ap.add_argument("--stats", action="store_true", help="μόνο μετρήσεις, δεν γράφει")
    ap.add_argument("--profile", default="board", choices=sorted(PROFILES),
                    help="ποιου agent το corpus (προεπιλογή: board)")
    ap.add_argument("--all", action="store_true", help="χτίσε όλα τα προφίλ")
    args = ap.parse_args()
    if args.all:
        rc = 0
        for name in sorted(PROFILES):
            print(chr(10) + "-- PROFIL: " + name + " --")
            rc |= build(name, args.stats)
        return rc
    return build(args.profile, args.stats)


def build(profile: str, stats_only: bool) -> int:
    prof = PROFILES[profile]
    files = [(n, t) for n, t in REQ_FILES if n in prof["files"]]
    out_path = OUT_DIR / f"context-{profile}.md"

    idx = index_all(REQ_FILES)          # ο γράφος links δείχνει παντού
    CORPUS_IDS.clear()
    CORPUS_IDS.update(r for n, _ in files for r in
                      [x.get("id") for x in load(n).get("requirements", [])] if r)
    # Οι δανεικές μετράνε ως «μέσα στο corpus»: αλλιώς κάθε παραπομπή σε αυτές
    # θα ενσωματωνόταν ξανά αυτούσια αντί να δείχνει στο μπλοκ τους.
    CORPUS_IDS.update(prof.get("extra_ids", []))
    INLINED.clear()                     # ένα corpus, ένα σύνολο «ήδη τυπωμένων»
    # Οι σημειώσεις 7-8 είναι η ΣΥΝΕΧΕΙΑ της απαρίθμησης του HEAD, άρα κολλάνε
    # πάνω στο σημείο 6 χωρίς κενή γραμμή (βλ. READ_NOTES: μόνο όπου υπάρχουν
    # απαιτήσεις — ο `remarks` και ο `description` κρατούν το HEAD ως έχει).
    parts: list[str] = [HEAD.rstrip() + chr(10) + READ_NOTES if files else HEAD]

    # ── ΤΑ ΓΕΓΟΝΟΤΑ ΤΟΥ SYLLABUS ────────────────────────────────────────────
    # Πρώτα, γιατί σχεδόν κάθε ερώτηση για κατώφλια τα χρειάζεται, και γιατί
    # είναι ο ΜΟΝΟΣ τρόπος να υπολογιστεί το ΠΔ άρθρο 3 παρ.1δ.
    fc = json.loads((ROOT / "data" / "flowchart2.json").read_text(encoding="utf-8"))
    air = [s for s in fc["sorties"] if s.get("band") == "flights"]
    from collections import Counter
    per = Counter(s["track"] for s in air)
    con = [s["uid"].replace("s:", "") for s in air if s["track"] == "contact"]
    pre = con.index("C4791") + 1
    parts.append(
        "## ΤΑ ΑΡΙΘΜΗΤΙΚΑ ΓΕΓΟΝΟΤΑ ΤΟΥ ΣΤΑΔΙΟΥ (Phase II)\n\n"
        f"- ΣΥΝΟΛΟ ΠΤΗΣΕΩΝ ΑΕΡΟΣ: **{len(air)}** — "
        + " · ".join(f"{k} {v}" for k, v in sorted(per.items()))
        + "\n  Τυπωμένο σε ΔΥΟ σημεία που συμφωνούν: Syllabus σελ.PDF 163 και 3-01 Πίνακας 1 (σελ.PDF 37).\n"
        f"- ΦΑΣΗ «ΠΡΟ ΜΟΝΟΣ»: **{pre}** πτήσεις (14 συγκυβέρνησης + 1 ΜΟΝΟΣ), "
        "τελειώνει στην C4791. Τυπωμένο στον πίνακα MIF «CONTACT (PRE-SOLO) / T-6A», Syllabus σελ.PDF 92.\n"
        "- Η C4790 είναι η **Αξιολόγηση** για τη ΜΟΝΟΣ και η C4791 η **πρώτη ΜΟΝΟΣ**· "
        "πετιούνται την ίδια μέρα με το ίδιο Α/Φ, και κατά 3-01 §55 μετρούν ως **μία έξοδος** για τη μέγιστη απασχόληση.\n"
        f"- ΑΡΑ ΠΔ άρθρο 3 παρ.1δ: 40% × {pre} = **6** πτήσεις 0-59% στην ΠΡΟ ΜΟΝΟΣ · "
        f"20% × {len(air)} = **17** στο Στάδιο. ✓ ΑΠΟΦΑΝΣΗ ιδιοκτήτη 17/10/2026: ο παρονομαστής είναι "
        "το **τυπωμένο πρόγραμμα**, όχι οι μέχρι τώρα εκτελεσμένες — «όχι σε όσες έχει πετάξει μέχρι "
        "τώρα, αλλά στο σύνολο, είτε για το προ-μόνος είτε για όλο το στάδιο».\n"
    )

    # ── Η ΣΕΙΡΑ ΤΩΝ ΕΞΟΔΩΝ (board, full) — αμέσως μετά τα αριθμητικά γεγονότα ──
    if prof.get("order"):
        parts.append("\n".join(render_order(fc)) + "\n")

    # ── ΟΙ ΠΕΝΤΕ ΟΜΑΔΕΣ ΑΠΑΙΤΗΣΕΩΝ ──────────────────────────────────────────
    counts = {}
    for name, title in files:
        d = load(name)
        rs = sorted(d.get("requirements", []), key=lambda r: str(r.get("id")))
        counts[name] = len(rs)
        parts.append(f"\n## {title} ({len(rs)} απαιτήσεις)\n")
        if d.get("scope"):
            parts.append(f"ΕΜΒΕΛΕΙΑ: {clean(d['scope'])}\n")
        # Οι εσωτερικές παραπομπές ενσωματώνονται ΜΟΝΟ στις αποτυχίες: εκεί ζει
        # το πρόβλημα που ανέφερε ο ιδιοκτήτης, και εκεί κοστίζει ο πηγαιμός.
        inline = name == "failure_procedures.json"
        for r in rs:
            parts.extend(render_req(r, idx, inline))

    # ── ΟΙ ΔΑΝΕΙΚΕΣ ΑΠΑΙΤΗΣΕΙΣ ──────────────────────────────────────────────
    # Χωριστό τμήμα, με ρητό τίτλο: ο agent πρέπει να ξέρει ότι αυτά έρχονται
    # από το αρχείο των αποτυχιών, όχι από τη ροή — η ΠΗΓΗ τους το λέει ούτως
    # ή άλλως, αλλά ο τίτλος το κάνει αδύνατο να το προσπεράσει.
    extra = [i for i in prof.get("extra_ids", []) if i in idx]
    if extra:
        missing = [i for i in prof.get("extra_ids", []) if i not in idx]
        if missing:                      # id που δεν υπάρχει = σιωπηλό κενό
            raise SystemExit(f"extra_ids που δεν υπάρχουν: {missing}")
        parts.append(f"\n## ΔΙΑΤΑΞΕΙΣ ΑΠΟΤΥΧΙΑΣ ΠΟΥ ΚΥΒΕΡΝΟΥΝ ΤΗ ΡΟΗ ({len(extra)} απαιτήσεις)\n")
        parts.append("Από το αρχείο των αποτυχιών, γιατί οι κανόνες της ροής τις "
                     "επικαλούνται ονομαστικά και χωρίς αυτές δεν τεκμηριώνονται.\n")
        for i in extra:
            parts.extend(render_req(idx[i], idx, False))

    if prof["board"]:
        parts.extend(render_matrix(load("board_tolerance_matrix.json"), idx))
        parts.extend(render_trees(load("board_decision_trees.json")))

    # Τα αυτούσια αρχεία ΤΕΛΕΥΤΑΙΑ και με σταθερή σειρά: ό,τι μπαίνει μετά το
    # breakpoint του cache δεν πρέπει ποτέ να μετακινηθεί.
    for rel in prof.get("extras", []):
        raw = (ROOT / rel).read_text(encoding="utf-8")
        parts.append(chr(10) + chr(10) + "## ΑΥΤΟΥΣΙΟ ΑΡΧΕΙΟ: " + rel + chr(10))
        parts.append("Αυτό είναι το ΣΥΜΒΟΛΑΙΟ, όχι περίληψή του. Ό,τι γράφεις υπακούει εδώ." + chr(10))
        parts.append("```" + chr(10) + raw.rstrip() + chr(10) + "```")

    body = "\n".join(parts).rstrip() + "\n"
    digest = hashlib.md5(body.encode("utf-8")).hexdigest()
    body += f"\n<!-- corpus-md5: {digest} -->\n"

    chars = len(body)
    print(f"απαιτήσεις: {sum(counts.values())}  " + " · ".join(f"{k.split('.')[0]}={v}" for k, v in counts.items()))
    print(f"μέγεθος: {chars:,} χαρακτήρες  ≈ {chars // 25 * 10:,}–{chars // 2:,} tokens (ελληνικά)")
    print(f"md5: {digest}")

    if stats_only:
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out_path.write_text(body, encoding="utf-8", newline="\n")
    print(f"→ {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
