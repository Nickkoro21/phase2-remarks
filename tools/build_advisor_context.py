# επαναλαμβάνεται η αποποίηση 355 φορές, και ο agent δεν μπορεί να μπερδέψει
# σημαία με διάταξη.
# ΤΙ ΔΕΝ ΕΙΝΑΙ ΟΜΟΙΟΓΕΝΕΣ. Οι 355 δεν είναι όλες αμφιβολίες: 27 φέρουν ρητό
# πρόθεμα που δηλώνει το ΑΝΤΙΣΤΡΟΦΟ ή απλή τεκμηρίωση (ΣΥΓΚΛΙΣΗ 11, ΠΑΡΑΓΩΓΗ
# ΤΙΜΗΣ 7, ΕΝΤΟΣ ΠΕΡΙΜΕΤΡΟΥ 3, ΣΥΜΦΩΝΙΑ/ΤΕΚΜΗΡΙΩΣΗ/ΔΙΟΡΘΩΣΗ/ΣΗΜΕΙΩΣΗ κ.λπ.), και
# 258 δεν φέρουν κανένα πρόθεμα. ΔΕΝ τις ταξινομούμε με ευρετικές επί του
# κειμένου — μια λάθος ταξινόμηση είναι χειρότερη από μία ειλικρινή κεφαλίδα.
# Αντ' αυτού το λέει η §9 των σημειώσεων ανάγνωσης.
def flags_block(r: dict, indent: str = "") -> list[str]:
    fl = [clean(f) for f in (r.get("flags") or []) if clean(f)]
    if not fl:
        return []
    out = [f"{indent}⚠ ΟΙ ΣΗΜΕΙΩΣΕΙΣ ΤΗΣ ΨΗΦΙΟΠΟΙΗΣΗΣ ΓΙ' ΑΥΤΗ ΤΗΝ ΑΠΑΙΤΗΣΗ"
           f" ({len(fl)}) — ΑΜΦΙΒΟΛΙΑ, ΟΧΙ ΚΑΝΟΝΑΣ:"]
    out.extend(f"{indent}  ⚠ ΑΛΥΤΟ: {f}" for f in fl)
    return out


def inline_full(lr: dict) -> list[str]:
    """Η ΟΛΟΚΛΗΡΗ απαίτηση μέσα σε bullet, για id που δεν τυπώνεται αλλού.
    13 ids `ft-*` φτάνουν στο corpus του `board` ΜΟΝΟ έτσι (το
    `flight_training.json` είναι εκτός του προφίλ), και ένα πεδίο δεν αρκεί: το
    `ft-126` «Κριτήρια παραπομπής σε κρίση Πτητικής Καταλληλότητας» έχει
    αυτολεξεί 775 χαρακτήρων αλλά ΑΠΑΙΤΗΣΗ 2.083 — τα εδάφια α και στ…ιβ ζουν
    μόνο στο δεύτερο. Όταν το αντίγραφο είναι μοναδικό, μπαίνει ακέραιο."""
    pad = "    "
    out = [f"  • [{lr.get('id')}] {clean(lr.get('topic'))}"
           " — ΔΕΝ έχει δικό του μπλοκ σε αυτό το corpus, γι' αυτό μπαίνει εδώ ΟΛΟΚΛΗΡΟ:"]
    if lr.get("requirement"):
        out.append(f"{pad}ΑΠΑΙΤΗΣΗ: {clean(lr['requirement'])}")
    if lr.get("verbatim"):
        out.append(f"{pad}ΑΥΤΟΛΕΞΕΙ: {clean(lr['verbatim'])}")
    if lr.get("values"):
        out.extend(values_block(lr["values"], f"{pad}ΤΙΜΕΣ:", pad + "  "))
    for step in lr.get("procedure") or []:
        out.append(f"{pad}→ {clean(step)}")
    if src_of(lr):
        out.append(f"{pad}ΠΗΓΗ: {src_of(lr)}")
    # ΑΚΕΡΑΙΟ ΣΗΜΑΙΝΕΙ ΚΑΙ ΤΙΣ ΑΜΦΙΒΟΛΙΕΣ. Τα 13 ορφανά `ft-*` του `board` έχουν
    # 5 σημαίες συνολικά· αν δεν μπουν εδώ, χάνονται από το corpus του board
    # εντελώς, αφού δικό τους μπλοκ δεν υπάρχει. 5 σημειώσεις, μηδαμινό κόστος.
    out.extend(flags_block(lr, pad))
    return out


def render_req(r: dict, idx: dict, inline: bool) -> list[str]:
    """Μία απαίτηση. `inline`: ενσωμάτωσε το κείμενο όσων παραπέμπει."""
    out = [f"### [{r.get('id')}] {clean(r.get('topic'))}"]
    if r.get("requirement"):
        out.append(clean(r["requirement"]))
    if r.get("verbatim"):
        out.append(f"> ΑΥΤΟΛΕΞΕΙ: {clean(r['verbatim'])}")
    if r.get("values"):
        out.extend(values_block(r["values"], "ΤΙΜΕΣ:"))
    for step in r.get("procedure") or []:
        out.append(f"  → {clean(step)}")
    if src_of(r):
        out.append(f"ΠΗΓΗ: {src_of(r)}")
    # Οι σημαίες ΠΡΙΝ από τις ενσωματωμένες παραπομπές: ανήκουν σε ΑΥΤΗ την
    # απαίτηση, και μετά το κείμενο των γειτόνων θα διαβάζονταν ως δικές τους.
    out.extend(flags_block(r))

    # ── ΟΙ ΠΑΡΑΠΟΜΠΕΣ ΜΕΣΑ ΣΤΗΝ ΠΑΡΑΠΟΜΠΗ ──────────────────────────────────
    # Μόνο όταν το ίδιο το κείμενο παραπέμπει κάπου (XREF) — αλλιώς το corpus
    # θα τριπλασιαζόταν αντιγράφοντας γειτονιές που κανείς δεν ρώτησε.
    links = [l for l in (r.get("links") or []) if l in idx]
    if inline and links and XREF.search((r.get("verbatim") or "") + (r.get("requirement") or "")):
        out.append("ΤΟ ΚΕΙΜΕΝΟ ΤΩΝ ΠΑΡΑΠΟΜΠΩΝ ΤΟΥ (ώστε να μη χρειάζεται να πας αλλού):")
        for lid in sorted(links):
            lr = idx[lid]
            if lid in INLINED:
                # ΔΕΥΤΕΡΗ ΦΟΡΑ: ΔΕΙΚΤΗΣ ΠΟΥ ΟΝΟΜΑΤΙΖΕΙ, ΔΕΝ ΚΑΤΕΥΘΥΝΕΙ. Ο παλιός
                # δείκτης έλεγε «δόθηκε παραπάνω» και σε 20 από τις 70 εμφανίσεις
                # (10 ids: fail-32/37/44/62/64/73/85/88, gt-45, gt-54) το πλήρες
                # `### [id]` μπλοκ είναι ΑΠΟ ΚΑΤΩ — η πρώτη ενσωμάτωση είχε
                # τυπώσει μόνο το αυτολεξεί, και το μπλοκ έρχεται αργότερα κατά
                # σειρά ids ή σε επόμενο αρχείο. Καμία απώλεια, αλλά η οδηγία
                # έστελνε το μοντέλο προς τα πάνω να ψάξει κάτι που ήταν κάτω.
                # Τώρα ο δείκτης λέει ΤΟ ID: αληθεύει και στις δύο κατευθύνσεις.
                if lid in CORPUS_IDS:
                    out.append(f"  • [{lid}] {clean(lr.get('topic'))} — (η ΠΛΗΡΗΣ απαίτηση είναι"
                               f" στο δικό της μπλοκ «### [{lid}]» μέσα σε αυτό το corpus"
                               " — ψάξε το id, μπορεί να είναι πιο πάνω ή πιο κάτω)")
                else:
                    # Ορφανό id (τα 13 `ft-*` του board): δικό του μπλοκ ΔΕΝ
                    # υπάρχει, το μοναδικό ακέραιο αντίγραφο είναι η πρώτη
                    # ενσωμάτωση — και αυτή είναι όντως παραπάνω.
                    out.append(f"  • [{lid}] {clean(lr.get('topic'))} — (δεν έχει δικό του μπλοκ"
                               " σε αυτό το corpus· το πλήρες κείμενο δόθηκε ΠΑΡΑΠΑΝΩ, στην πρώτη"
                               " ενσωμάτωσή του)")
                continue
            INLINED.add(lid)
            if lid in CORPUS_IDS:
                # Έχει δικό του μπλοκ εδώ μέσα, άρα αρκεί το αυτολεξεί — ΑΛΛΑ
                # ΑΚΕΡΑΙΟ. Το παλιό `[:600]` έκοβε 32 bullets στη μέση λέξης,
                # ενώ ο agent έχει ρητή εντολή να παραθέτει αυτολεξεί. Το
                # μετρημένο κόστος της κατάργησης είναι 4.709 χαρακτήρες.
                t = clean(lr.get("verbatim")) or clean(lr.get("requirement"))
                out.append(f"  • [{lid}] {clean(lr.get('topic'))} — {t}")
            else:
                out.extend(inline_full(lr))
    elif links:
        out.append("ΣΧΕΤΙΚΑ: " + ", ".join(sorted(links)))
    out.append("")
    return out


def render_matrix(d: dict, idx: dict) -> list[str]:
    out = ["", "## Ο ΣΥΓΚΕΝΤΡΩΤΙΚΟΣ ΠΙΝΑΚΑΣ ΑΝΟΧΗΣ — «ΠΟΣΕΣ ΦΟΡΕΣ ΧΩΡΙΣ ΣΥΜΒΟΥΛΙΟ»", ""]
    for note in d.get("reading_notes") or []:
        out.append(f"ΣΗΜΕΙΩΣΗ ΑΝΑΓΝΩΣΗΣ: {clean(note)}")
    out.append("")
    # Σκάλα → το `failure_kind` που την τύπωσε πρώτο. Δύο σκάλες επαναλαμβάνονται
    # σε 4 και 3 εγγραφές αντίστοιχα, πανομοιότυπες γραμμή προς γραμμή.
    ladders: dict[tuple, str] = {}
    for e in d.get("entries", []):
        kind = clean(e.get("failure_kind"))
        out.append(f"### {kind}")
        a = e.get("allowed_before_board") or {}
        if a.get("statement"):
            out.append(clean(a["statement"]))
        # ΤΟ ΜΗΔΕΝ ΤΩΝ ΕΝΔΙΑΜΕΣΩΝ ΕΞΕΤΑΣΕΩΝ ΕΞΑΦΑΝΙΖΟΤΑΝ. Η clean() κάνει
        # `str(s or "")`: σε 5 εγγραφές (1στ, 1η, 1θ, 1ι, ατύχημα) το
        # `checks_between_referral_and_board` είναι ΑΚΕΡΑΙΟ 0 και τυπωνόταν
        # ΚΕΝΟ — ενώ η σημείωση ανάγνωσης λέει ρητά «οδηγούν ΑΠΕΥΘΕΙΑΣ στο
        # Συμβούλιο: = 0». Το `_scalar` δίνει «0», και «null» όπου η τιμή δεν
        # ορίζεται στις πηγές, όπως λέει η ίδια η σημείωση (ΟΧΙ «None»).
        out.append(
            f"ΑΝΕΚΤΑ ΠΕΡΙΣΤΑΤΙΚΑ ΠΡΙΝ ΤΗΝ ΚΡΙΣΗ: {_scalar(a.get('occurrences_tolerated_before_referral'))}"
            f" · ΕΝΔΙΑΜΕΣΕΣ ΕΞΕΤΑΣΕΙΣ: {_scalar(a.get('checks_between_referral_and_board'))}"
        )
        lad = tuple(clean(x) for x in e.get("ladder") or [])
        if lad and lad in ladders:
            out.append(f"  → (Η ΣΚΑΛΑ ΕΙΝΑΙ Η ΙΔΙΑ, γραμμή προς γραμμή, με «{ladders[lad]}» παραπάνω.)")
        else:
            if lad:
                ladders[lad] = kind
            for rung in lad:
                out.append(f"  → {rung}")
        if e.get("threshold_verbatim"):
            # ΤΟ ΙΔΙΟ ΕΔΑΦΙΟ ΔΥΟ ΦΟΡΕΣ ΔΕΝ ΕΙΝΑΙ ΔΥΟ ΕΔΑΦΙΑ. Και τα 23
            # `threshold_verbatim` είναι ταυτόσημα — χαρακτήρα προς χαρακτήρα,
            # ελεγμένο εδώ και όχι υποτεθέν — με το αυτολεξεί της
            # `primary_requirement`, που τυπώνεται πλήρης παραπάνω. Ο δείκτης
            # ΟΝΟΜΑΤΙΖΕΙ το id (που ο πίνακας δεν έλεγε πριν): κερδίζει
            # πληροφορία, δεν χάνει. Αν κάποιο ΔΕΝ ταυτίζεται, ή η απαίτηση δεν
            # είναι σε αυτό το προφίλ, τυπώνεται ακέραιο όπως πάντα.
            prim = clean(e.get("primary_requirement"))
            tv = clean(e["threshold_verbatim"])
            twin = prim in CORPUS_IDS and clean((idx.get(prim) or {}).get("verbatim")) == tv
            out.append(
                f"> ΑΥΤΟΛΕΞΕΙ: ταυτόσημο, χαρακτήρα προς χαρακτήρα, με το ΑΥΤΟΛΕΞΕΙ "
                f"της απαίτησης [{prim}] — τυπωμένο πλήρες εκεί."
                if twin else f"> ΑΥΤΟΛΕΞΕΙ: {tv}"
            )
        ids = sorted({clean(s.get("requirement_id")) for s in e.get("sources") or [] if s.get("requirement_id")})
        if ids:
            out.append("ΑΠΑΙΤΗΣΕΙΣ: " + ", ".join(ids))
        out.append("")
    return out


def render_trees(d: dict) -> list[str]:
    out = ["", "## ΤΑ ΔΕΝΤΡΑ ΑΠΟΦΑΣΕΩΝ ΤΟΥ ΣΥΜΒΟΥΛΙΟΥ", ""]
    if d.get("rule"):
        out.append(f"ΚΑΝΟΝΑΣ: {clean(d['rule'])}")
    trees = d.get("trees") or []
    if isinstance(trees, dict):
        trees = [dict(v, id=k) for k, v in sorted(trees.items())]
    for t in sorted(trees, key=lambda x: str(x.get("id") or x.get("key") or "")):
        out.append(f"### ΟΙΚΟΓΕΝΕΙΑ: {clean(t.get('title') or t.get('id'))}")
        nodes = t.get("nodes") or []
        if isinstance(nodes, dict):
            nodes = [dict(v, id=k) for k, v in sorted(nodes.items())]
        for n in nodes:
            out.append(f"— ΚΟΜΒΟΣ [{clean(n.get('id'))}] {clean(n.get('label'))}")
            for fld, lab in (("condition", "ΣΥΝΘΗΚΗ"), ("threshold", "ΚΑΤΩΦΛΙ"),
                             ("outcome", "ΕΚΒΑΣΗ"), ("next_with", "ΠΕΤΑΕΙ ΜΕΤΑ ΜΕ")):
                if n.get(fld):
                    out.append(f"   {lab}: {clean(n[fld])}")
            for c in n.get("cites") or []:
                rid = clean(c.get("requirement_id"))
                # ΟΧΙ ΔΕΥΤΕΡΗ ΦΟΡΑ ΤΟ ΙΔΙΟ ΚΕΙΜΕΝΟ. Αν η απαίτηση τυπώνεται ήδη
                # παραπάνω με το id της, εδώ αρκεί ο δείκτης: 143 παραπομπές ×
                # 500 χαρακτήρες είναι ~7% του corpus σε καθαρή επανάληψη, και
                # ένα μοντέλο που βλέπει το ίδιο εδάφιο δύο φορές δεν μαθαίνει
                # περισσότερα — μπερδεύεται για το αν είναι δύο διαφορετικά.
                # Η ΛΑΝΘΑΝΟΥΣΑ ΑΠΟΚΟΠΗ ΕΦΥΓΕ. Εδώ έμενε ένα `[:500]` για τις
                # παραπομπές σε ids εκτός CORPUS_IDS. Σήμερα είναι ανενεργό
                # (και στα 143 cites των δέντρων, 0 δείχνουν εκτός corpus — σε
                # board ΚΑΙ σε full), αλλά 50 από τα 143 αυτολεξεί ξεπερνούν τους
                # 500 χαρακτήρες (μέγιστο 1.093): την πρώτη μέρα που ένα δέντρο
                # παραπέμψει σε απαίτηση άλλου αρχείου θα έκοβε σιωπηλά στη μέση
                # λέξης, ενώ το docstring υπόσχεται «ΠΟΥΘΕΝΑ αποκοπή». Τηρούμε
                # την υπόσχεση αντί να τη σχολιάζουμε.
                known = rid in CORPUS_IDS
                tail = "(το πλήρες κείμενο παραπάνω, με αυτό το id)" if known \
                    else clean(c.get("verbatim"))
                out.append(
                    f"   ΠΑΡΑΠΟΜΠΗ [{rid}] {clean(c.get('ref'))}"
                    f" (σελ.PDF {c.get('page_pdf')}): {tail}"
                )
                if c.get("explanation"):
                    out.append(f"      ΕΡΜΗΝΕΙΑ: {clean(c['explanation'])}")
            for rl in n.get("rulings") or []:
                out.append(
                    f"   ✓ ΑΠΟΦΑΝΣΗ {clean(rl.get('date'))} ({clean(rl.get('by'))}): {clean(rl.get('text'))}"
                )
                if rl.get("quote"):
                    out.append(f"      ΜΕ ΤΑ ΛΟΓΙΑ ΤΟΥ: «{clean(rl['quote'])}»")
            for u in n.get("unresolved") or []:
                out.append(f"   ⚠ ΑΛΥΤΟ: {clean(u)}")
        out.append("")
    return out


TRACKS = [("contact", "ΠΡΟΣΑΡΜΟΓΗ (contact)"), ("instrument", "ΟΡΓΑΝΑ (instrument)"),
          ("formation", "ΣΧΗΜΑΤΙΣΜΟΣ (formation)"), ("vfr_navigation", "ΝΑΥΤΙΛΙΑ (vfr_navigation)")]


def render_order(fc: dict) -> list[str]:
    """Η ΣΕΙΡΑ ΤΩΝ ΕΞΟΔΩΝ — πίνακας, όχι πρόζα. Η σειρά του flowchart2.json ΕΙΝΑΙ
    η τυπωμένη σειρά του προγράμματος ανά κατηγορία (έτσι μετρά και ο
    υπολογισμός της ΠΡΟ-ΜΟΝΟΣ παραπάνω). Μόνο γεγονότα: κωδικός, ενότητα,
    τίτλος, ώρες, σημαίες — κανένας κανόνας χωρίς παραπομπή εδώ."""
    out = ["", "## Η ΣΕΙΡΑ ΤΩΝ ΕΞΟΔΩΝ ΤΟΥ ΠΡΟΓΡΑΜΜΑΤΟΣ (από το data/flowchart2.json)", "",
           "ΠΩΣ ΔΙΑΒΑΖΕΤΑΙ: α/α στην κατηγορία · κωδικός · ενότητα · τίτλος · ώρες · σημαίες. "
           "ΑΞ = Αξιολόγηση (checkride) · ΜΟΝΟΣ = η πρώτη ΜΟΝΟΣ · (Μ) = έξοδος που μπορεί να πεταχτεί ΜΟΝΟΣ · "
           "Ν = νυχτερινή. «Πριν/μετά» μεταξύ δύο εξόδων της ίδιας κατηγορίας σημαίνει τη θέση τους σε αυτή τη λίστα. "
           "Οι κατηγορίες τρέχουν παράλληλα — η λίστα δεν λέει ποια κατηγορία πετιέται πρώτη.", ""]
    for band, lab in (("flights", "ΑΕΡΟΣ"), ("fs", "F/S — εξομοιωτής")):
        for tr, tl in TRACKS:
            rows = [s for s in fc["sorties"] if s.get("band") == band and s.get("track") == tr]
            if not rows:
                continue
            out.append(f"### {lab} · {tl} — {len(rows)} έξοδοι")
            for i, s in enumerate(rows, 1):
                flags = [f for f, on in (("ΑΞ", s.get("checkride")), ("ΜΟΝΟΣ", s.get("first_solo")),
                                         ("(Μ)", s.get("solo_candidate") and not s.get("first_solo")),
                                         ("Ν", s.get("night"))) if on]
                h = f"{s['hours']}h" if s.get("hours") is not None else "—"
                out.append(f"{i:>2}. {s['id']} · {clean(s.get('section_verbatim'))} · {clean(s.get('name'))} · {h}"
                           + (" · " + " ".join(flags) if flags else ""))
            out.append("")
    return out


