# Οι δύο σημειώσεις ανάγνωσης μπαίνουν ΜΟΝΟ στα corpora που τυπώνουν απαιτήσεις.
# Ο `remarks` και ο `description` δεν έχουν ούτε `ΤΙΜΕΣ:` ούτε δείκτες, άρα θα
