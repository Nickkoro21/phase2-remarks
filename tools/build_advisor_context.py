# ── ΤΙΜΕΣ: ΔΕΔΟΜΕΝΑ, ΟΧΙ repr() ΤΗΣ PYTHON ──────────────────────────────────
# Το `values` δεν είναι επίπεδο λεξικό: έχει ένθετα λεξικά, λίστες εγγραφών και
# βάθος έως 4 (`gt-10.subjects`). Η παλιά γραμμή `f"{k}={v}"` έριχνε ωμό repr()
# σε 211 γραμμές — άγκιστρα, μονά εισαγωγικά, `True`/`None` της Python. Τυπώνει
# τα ΙΔΙΑ κλειδιά και τις ΙΔΙΕΣ τιμές, μία φορά την καθεμιά, με εσοχή για το
# βάθος: μηδενική απώλεια, και διαβάζεται και από άνθρωπο που ελέγχει το corpus.
def _scalar(v) -> str:
    """Τιμή-φύλλο σε γραφή JSON: `true/false/null` αντί `True/False/None`. Ίδια
    πληροφορία — απλώς η γραφή που έχουν και τα ίδια τα αρχεία των πηγών."""
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    # ΤΟ ΜΗΔΕΝ ΕΙΝΑΙ ΤΙΜΗ. Η clean() κάνει `str(s or "")`, άρα το 0 και το 0.0
    # γίνονται κενό — και το `[0, 59]` του `fail-04.grade_range_pct` θα γινόταν
    # `[, 59]`, δηλαδή σιωπηρή απώλεια κατωφλίου. Οι αριθμοί δεν περνούν από εκεί.
    if isinstance(v, (int, float)):
        return str(v)
    return clean(v)


def _leaf(v) -> bool:
    return not isinstance(v, (dict, list))


def fmt_values(val: dict, indent: str = "  ") -> list[str]:
    """Τα `values` σε γραμμές. Τα επίπεδα ζεύγη ενός επιπέδου μπαίνουν σε ΜΙΑ
    γραμμή χωρισμένα με ` · ` (γι' αυτό μέσα στις λίστες το `, ` παραμένει
    αδιάβλητο ως διαχωριστικό στοιχείων)· κάθε δοχείο ανοίγει δικό του μπλοκ."""
    flat: list[str] = []
    deep: list[tuple[str, object]] = []
    for k, v in sorted(val.items()):
        if _leaf(v):
            flat.append(f"{k}={_scalar(v)}")
        elif isinstance(v, list) and all(_leaf(x) for x in v):
            flat.append(f"{k}=[{', '.join(_scalar(x) for x in v)}]")
        else:
            deep.append((k, v))
    out = [indent + " · ".join(flat)] if flat else []
    for k, v in deep:
        if isinstance(v, dict):
            # Τα επίπεδα ζεύγη του ένθετου λεξικού ανεβαίνουν στη γραμμή του
            # κλειδιού (`total: hours=4:00 · sorties=4`): η άνω-κάτω τελεία το
            # ξεχωρίζει από ένα `κλειδί=τιμή` και γλιτώνει μισές γραμμές.
            out.extend(values_block(v, f"{indent}{k}:", indent + "  "))
            continue
        # Λίστα εγγραφών. Αριθμείται, γιατί η σειρά ΕΙΝΑΙ πληροφορία (σειρά
        # πίνακα της πηγής), και τα κλειδιά δεν είναι πάντα τα ίδια σε κάθε
        # εγγραφή (`cont-09.events`: 16 διαφορετικά σχήματα) — άρα ΟΧΙ πίνακας
        # με κοινή κεφαλίδα, που θα απαιτούσε κενά κελιά και θα έλεγε ψέματα.
        out.append(f"{indent}{k}: {len(v)} εγγραφές")
        for i, item in enumerate(v, 1):
            pad = indent + "     "
            if isinstance(item, dict):
                sub = fmt_values(item, pad)
                head = sub[0].strip() if sub and sub[0].strip() else ""
                out.append(f"{indent}  {i}) {head}".rstrip())
                out.extend(sub[1:] if head else sub)
            elif isinstance(item, list) and all(_leaf(x) for x in item):
                out.append(f"{indent}  {i}) [{', '.join(_scalar(x) for x in item)}]")
            elif _leaf(item):
                out.append(f"{indent}  {i}) {_scalar(item)}")
            else:
                # Σχήμα που δεν προβλέψαμε (λίστα σε λίστα με δοχεία μέσα). Ωμό
                # JSON, ΑΛΛΑ ΠΟΤΕ σιωπή: καλύτερα άσχημο παρά χαμένο.
                out.append(f"{indent}  {i}) " + json.dumps(item, ensure_ascii=False, sort_keys=True))
    return out


def values_block(vals: dict, label: str, indent: str = "  ") -> list[str]:
    """`ΤΙΜΕΣ: …` με τα επίπεδα ζεύγη ΠΑΝΩ στην ετικέτα — τα ένθετα μπλοκ από
    κάτω. Ο λόγος είναι η ανάγνωση: η συντριπτική πλειονότητα των απαιτήσεων
    έχει μόνο επίπεδα ζεύγη και πρέπει να μένει μονόγραμμη, όπως πριν."""
    lines = fmt_values(vals, indent)
    head = lines[0].strip() if lines and lines[0].strip() else ""
    return [label + (" " + head if head else "")] + (lines[1:] if head else lines)


